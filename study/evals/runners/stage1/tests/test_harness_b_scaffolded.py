"""The B_scaffolded arm (R45): prompt provenance, no honoring language, and a live mock run.

The prompt is generated by tools/derive_b_scaffolded.py from the frozen affordances schema; these
tests bind the committed prompt to its generator, assert the arm carries no honoring or structural
claims (the axis it must not touch), and prove the harness can actually run the condition.
"""
import importlib.util
import json
import os
import shutil
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from test_harness_fix9 import _mock_run, _scenario  # noqa: E402

from harness import runner  # noqa: E402

PROMPTS = os.path.join(ROOT, "harness", "prompts")


def _read(name):
    with open(os.path.join(PROMPTS, name), "r", encoding="utf-8") as handle:
        return handle.read()


def _load_generator():
    path = os.path.join(ROOT, "tools", "derive_b_scaffolded.py")
    spec = importlib.util.spec_from_file_location("derive_b_scaffolded", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules["derive_b_scaffolded"] = module
    spec.loader.exec_module(module)
    return module


class ScaffoldedPromptTest(unittest.TestCase):
    def test_committed_prompt_matches_regeneration(self):
        generator = _load_generator()
        prompt, record = generator.build_prompt()
        self.assertEqual(_read("condition_B_scaffolded.md"), prompt)
        with open(os.path.join(ROOT, "..", "..", "..", "docs", "review", "b-scaffolded",
                               "DERIVATION_RECORD.md"), "r", encoding="utf-8") as handle:
            self.assertEqual(handle.read(), record)

    def test_skeleton_is_condition_b(self):
        action = _read("condition_B.md").split("\n\n")
        scaffolded = _read("condition_B_scaffolded.md").split("\n\n")
        self.assertEqual(scaffolded[0], action[0])            # working-directory opener
        self.assertEqual(scaffolded[1], action[1])            # the three plain tools
        self.assertEqual(scaffolded[-1], action[-1])          # closing STATUS instructions
        umbrella = action[2].split(". ", 1)[0] + "."
        self.assertTrue(scaffolded[2].startswith(umbrella))   # B's umbrella sentence, verbatim

    def test_no_honoring_or_structural_claims(self):
        prose = _read("condition_B_scaffolded.md").lower()
        for fragment in ("stops task execution", "is recorded", "recorded event",
                         "action stops", "honored", "honoring", "until the operator resolves"):
            self.assertNotIn(fragment, prose, f"honoring-axis fragment survived: {fragment!r}")

    def test_every_schema_slot_is_named(self):
        with open(os.path.join(ROOT, "harness", "affordances.schema.json"), encoding="utf-8") as handle:
            schema = json.load(handle)
        prose = _read("condition_B_scaffolded.md").lower()
        adapted = {"task_ref", "blocking_scope", "suggested_duration_seconds", "task_reference",
                   "reason", "alternative", "mode", "tool_call_id", "deny_pattern",
                   "tool_classes"}  # adapted or omitted wording, per the record
        for name, definition in schema["$defs"].items():
            if name == "task_ref":
                continue
            for field, prop in definition.get("properties", {}).items():
                if field in adapted or "$ref" in prop:
                    continue
                fragment = prop["description"].split(".")[0].strip().lower()
                self.assertIn(fragment[:40], prose,
                              f"{name}.{field} slot not named: {fragment!r}")

    def test_machinery_slots_are_omitted_and_recorded(self):
        prose = _read("condition_B_scaffolded.md").lower()
        for machinery in ("tool_call_id", "deny_pattern", "tool_classes", "host"):
            self.assertNotIn(machinery, prose, f"machinery leaked into the prose: {machinery!r}")
        with open(os.path.join(ROOT, "..", "..", "..", "docs", "review", "b-scaffolded",
                               "DERIVATION_RECORD.md"), "r", encoding="utf-8") as handle:
            record = handle.read()
        for fragment in ("Tool classes covered", "Identifier of a pending tool call",
                         "deny rule pattern"):
            self.assertIn(fragment, record, f"omission not recorded: {fragment!r}")

    def test_condition_profile_offers_no_tools(self):
        profile = runner.CONDITION_PROFILES["B_scaffolded"]
        self.assertFalse(profile["tools"])
        self.assertFalse(profile["honored"])
        self.assertEqual(profile["profile"], "unsupported")


class ScaffoldedMockRunTest(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="b-scaffolded-")
        self.addCleanup(shutil.rmtree, self.root, True)

    def test_mock_run_completes_in_b_scaffolded(self):
        scenario = _scenario("f2-01-missing-endpoint")
        record, run = _mock_run(scenario, "B_scaffolded", [],
                                os.path.join(self.root, "run"))
        self.assertEqual(record["condition"], "B_scaffolded")
        # No structured tools may be offered in this arm.
        self.assertFalse([tool for tool in getattr(run, "tools", []) or []
                          if str(tool).startswith("agency_layer")])
        transcript = record.get("system_prompt") or ""
        if transcript:
            self.assertIn("Five further actions", transcript)


if __name__ == "__main__":
    unittest.main()
